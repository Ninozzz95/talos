/**
 * Build the PDF font pack: three Roboto weights, subset to what Italian
 * business prose actually uses, as a pdfmake virtual file system.
 *
 * Run once, by hand, and COMMIT the result. It is a build-time step on a
 * developer machine, not something the app does: pdfmake's VFS is a plain
 * `{ filename: base64 }` object, so producing it needs no runtime tooling.
 *
 *   node scripts/build-pdf-fonts.mjs
 *
 * Why subset at all: pdfmake's stock font bundle is 834 KB (457 KB gzipped)
 * for four full weights. Latin-1 plus the euro sign and typographic
 * punctuation is 221 codepoints out of 927, which measures ten times smaller —
 * and TALOS will be distributed, so every kilobyte is shipped to everyone.
 *
 * Why not subset at runtime: pdfkit already subsets on embed, so the PDF that
 * comes out contains only the glyphs it used either way. Runtime subsetting
 * would cost 146 KB of fontkit to save nothing.
 *
 * Bold-italic is deliberately absent. A report does not need it, and it is a
 * whole weight of bytes for a style nothing in the generator emits.
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

// Latin basic + Latin-1 supplement + the euro + the punctuation a typographer
// actually reaches for. Anything outside this renders as a missing glyph, which
// is honest; the previous generator silently rewrote them to "?".
const UNICODES = [
    'U+0020-007E', // ASCII
    'U+00A0-00FF', // Latin-1: à è é ì ò ù ç ° « » …
    'U+20AC', // €
    'U+2013-2014', // – —
    'U+2018-201A,U+201C-201E', // curly quotes
    'U+2022,U+2026,U+2030,U+2039-203A,U+2122', // • … ‰ ‹ › ™
].join(',')

const WEIGHTS = [
    ['Roboto-Regular.ttf', 'Roboto-Regular.ttf'],
    ['Roboto-Medium.ttf', 'Roboto-Medium.ttf'],
    ['Roboto-Italic.ttf', 'Roboto-Italic.ttf'],
]

const source = 'node_modules/pdfmake/build/fonts/Roboto'
const work = mkdtempSync(join(tmpdir(), 'talos-fonts-'))
const vfs = {}

try {
    for (const [input, output] of WEIGHTS) {
        const target = join(work, output)
        // `python -m fontTools.subset` rather than the `pyftsubset` script:
        // the console entry point is not always on PATH, the module always is.
        execFileSync('python', [
            '-m', 'fontTools.subset',
            join(source, input),
            `--unicodes=${UNICODES}`,
            '--layout-features=',
            '--no-hinting',
            '--desubroutinize',
            `--output-file=${target}`,
        ], { stdio: 'inherit' })
        vfs[output] = readFileSync(target).toString('base64')
        console.log(`${output}: ${(readFileSync(target).length / 1024).toFixed(1)} KB`)
    }

    const banner = `/**
 * GENERATED by scripts/build-pdf-fonts.mjs — do not edit by hand.
 *
 * Roboto, subset to Latin-1 + euro + typographic punctuation, base64'd as a
 * pdfmake virtual file system. Regenerate with \`node scripts/build-pdf-fonts.mjs\`.
 */
`
    writeFileSync(
        'src/lib/documents/pdfFonts.ts',
        `${banner}export const TALOS_PDF_VFS: Record<string, string> = ${JSON.stringify(vfs, null, 0)}\n`,
        'utf8',
    )
    const bytes = readFileSync('src/lib/documents/pdfFonts.ts').length
    console.log(`\nsrc/lib/documents/pdfFonts.ts — ${(bytes / 1024).toFixed(1)} KB`)
} finally {
    rmSync(work, { recursive: true, force: true })
}
